"""Generates the small, disposable set of Xcode-visible files that make a
flow runnable: one JSON file per selected flow, a run_context.json for
human-playback pacing, and a single generated XCTestCase subclass with one
test method per flow.

Everything this module writes lives under .flow-review/generated/ (git
ignored) and is fully regenerated on every `flow-review run`/`init` -- it is
never hand-edited.
"""
from __future__ import annotations

import json
from pathlib import Path

from . import paths
from .flows import Flow
from .procutil import xcode_helper

GENERATED_TEST_CLASS = "FlowReviewGeneratedTests"


def generated_dir(project_root: Path, ui_test_target_name: str) -> Path:
    return paths.artifact_dir(project_root) / "generated" / ui_test_target_name


def _swift_test_file(flows: list[Flow]) -> str:
    lines = [
        "// GENERATED BY flow-review. Do not edit -- regenerated on every run.",
        "import XCTest",
        "",
        f"final class {GENERATED_TEST_CLASS}: FlowReviewTestCase {{",
    ]
    for flow in flows:
        lines.append(f"    func {flow.swift_test_name()}() throws {{")
        lines.append(f'        try runFlow(id: "{flow.id}")')
        lines.append("    }")
        lines.append("")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


_ENGINE_TEMPLATE_FILES = ["FlowModels.swift", "FlowEngine.swift", "FlowReviewTestCase.swift"]


def sync(
    project_root: Path,
    xcodeproj_path: Path,
    ui_test_target_name: str,
    flows: list[Flow],
    review_delay_ms: int,
) -> dict:
    """Writes generated Swift/JSON to disk and reconciles pbxproj membership."""
    project_root = project_root.resolve()
    xcodeproj_path = xcodeproj_path.resolve()
    gen_dir = generated_dir(project_root, ui_test_target_name)
    gen_dir.mkdir(parents=True, exist_ok=True)

    # Stable engine files (rarely change, but keep them in lockstep with the
    # tool version rather than trusting whatever was copied at `init` time).
    templates_dir = Path(__file__).parent / "templates" / "swift"
    for fname in _ENGINE_TEMPLATE_FILES:
        (gen_dir / fname).write_text((templates_dir / fname).read_text())

    for flow in flows:
        (gen_dir / f"{flow.id}.json").write_text(json.dumps(flow.to_json(), indent=2))

    (gen_dir / "run_context.json").write_text(
        json.dumps({"review_delay_ms": review_delay_ms}, indent=2)
    )

    (gen_dir / f"{GENERATED_TEST_CLASS}.swift").write_text(_swift_test_file(flows))

    # Remove on-disk leftovers from flows that were renamed/deleted since the
    # last sync -- otherwise their stale .json keeps its pbxproj membership
    # forever (sync_generated_group only ever reconciles against what's here).
    expected_names = set(_ENGINE_TEMPLATE_FILES) | {
        "run_context.json", f"{GENERATED_TEST_CLASS}.swift",
    } | {f"{flow.id}.json" for flow in flows}
    for existing in gen_dir.iterdir():
        if existing.is_file() and existing.name not in expected_names:
            existing.unlink()

    wanted_files = sorted(p.name for p in gen_dir.iterdir() if p.is_file())

    return xcode_helper("sync_generated_group", {
        "project_path": str(xcodeproj_path),
        "host_target_name": ui_test_target_name,
        "group_name": "FlowReviewGenerated",
        "folder_path": str(gen_dir),
        # Keep the Xcode project portable. `folder_path` is still used by the
        # helper to reconcile on-disk files, while this relative path is what
        # becomes part of project.pbxproj.
        "project_relative_folder_path": str(gen_dir.relative_to(project_root)),
        "files": wanted_files,
    })
